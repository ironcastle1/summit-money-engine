const express = require("express");
const { listFeatures } = require("../v6/featureRegistry");
const { listThreatTypes, classifyThreatText } = require("../v6/threatTaxonomy");
const { listCountryProfiles, getCountryProfile } = require("../v6/countryOperationalProfiles");
const { listSourcePipelines } = require("../v6/sourcePipelineRegistry");
const { estimateRadiusVerdict, verdictRuleBook } = require("../v6/verdictEngine");
const { routePlannerPlaybooks, routeRiskRules } = require("../v6/routePlannerPlaybooks");
const { buildOfflinePack } = require("../v6/offlinePackService");
const { listOperationalProcedures, proceduresForFeature } = require("../v6/operationalProcedureMatrix");
const router = express.Router();
router.get("/features", (req,res)=>res.json({features:listFeatures()}));
router.get("/threats", (req,res)=>res.json({threatTaxonomy:listThreatTypes()}));
router.post("/classify", (req,res)=>res.json({hits:classifyThreatText(req.body && req.body.text)}));
router.get("/countries", (req,res)=>res.json({countries:listCountryProfiles()}));
router.get("/country/:iso2", (req,res)=>res.json({country:getCountryProfile(req.params.iso2)}));
router.get("/sources", (req,res)=>res.json({sources:listSourcePipelines()}));
router.post("/verdict", (req,res)=>res.json(estimateRadiusVerdict(req.body||{})));
router.get("/verdict-rules", (req,res)=>res.json({rules:verdictRuleBook}));
router.get("/route-playbooks", (req,res)=>res.json({routePlannerPlaybooks, routeRiskRules}));
router.post("/offline-pack", (req,res)=>res.json(buildOfflinePack(req.body||{})));
router.get("/procedures", (req,res)=>res.json({procedures:listOperationalProcedures()}));
router.get("/procedures/:feature", (req,res)=>res.json({procedures:proceduresForFeature(req.params.feature)}));
module.exports = router;
